class AyahModel {
  final int surahNumber;
  final int ayahNumber;
  final String arabicText;
  final String somaliTranslation;
  final String footnotes;
  final int juzNumber;
  final int hizbNumber;

  const AyahModel({
    required this.surahNumber,
    required this.ayahNumber,
    required this.arabicText,
    required this.somaliTranslation,
    this.footnotes = '',
    this.juzNumber = 1,
    this.hizbNumber = 1,
  });

  factory AyahModel.fromJson(Map<String, dynamic> json, {int defaultJuz = 1, int defaultHizb = 1}) {
    return AyahModel(
      surahNumber: json['surah'] as int? ?? json['surah_number'] as int? ?? 1,
      ayahNumber: json['ayah'] as int? ?? json['ayah_number'] as int? ?? 1,
      arabicText: json['arabic_text'] as String? ?? '',
      somaliTranslation: json['translation'] as String? ?? json['somali_translation'] as String? ?? '',
      footnotes: json['footnotes'] as String? ?? '',
      juzNumber: defaultJuz,
      hizbNumber: defaultHizb,
    );
  }
}

