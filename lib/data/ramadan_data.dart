  /// Get lectures for a given scholar ID, ordered by sort_order
  static List<RamadanLecture> getLecturesByScholar(String scholarId) {
    final list = allLectures
        .where((l) => l.scholarId.toLowerCase() == scholarId.toLowerCase())
        .toList();
    list.sort((a, b) => a.sortOrder.compareTo(b.sortOrder));
    return list;
  }

  /// Get scholar metadata by ID
  static RamadanScholar? getScholarById(String scholarId) {
    final id = scholarId.toLowerCase();
    for (final s in scholars) {
      if (s.id.toLowerCase() == id) return s;
    }
    return null;
  }

  /// Get a single lecture by ID
  static RamadanLecture? getLectureById(String lectureId) {
    for (final l in allLectures) {
      if (l.id == lectureId) return l;
    }
    return null;
  }

  /// Validate CSV dataset integrity according to Section 6 of requirements
  static Map<String, dynamic> validateData() {
    final report = <String, dynamic>{
      'total_lectures': allLectures.length,
      'scholar_counts': <String, int>{},
      'duplicate_urls': <String, List<String>>{},
      'invalid_ids': <String>[],
    };

    final urlMap = <String, List<String>>{};
    for (final lecture in allLectures) {
      report['scholar_counts'][lecture.scholarId] =
          (report['scholar_counts'][lecture.scholarId] ?? 0) + 1;

      // Track duplicate URLs
      final normalizedUrl = lecture.youtubeUrl.trim();
      urlMap.putIfAbsent(normalizedUrl, () => []).add(lecture.id);

      if (lecture.videoId == null) {
        (report['invalid_ids'] as List<String>).add(lecture.id);
      }
    }

    for (final entry in urlMap.entries) {
      if (entry.value.length > 1) {
        report['duplicate_urls'][entry.key] = entry.value;
      }
    }

    return report;
  }
